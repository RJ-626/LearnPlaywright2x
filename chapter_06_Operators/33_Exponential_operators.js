//exponential operator is used to calculate the power of a number. It is represented by the double asterisk (**) symbol. The syntax for using the exponential operator is as follows:

console.log(2 ** 3); //8 (2 raised to the power of 3)

//You can also use the exponential operator with variables:
let base = 10;
let exponent = 3;
console.log(base ** exponent); //1000

