
//string concatenation is the process of combining two or more strings into a single string. In JavaScript, you can concatenate strings using the + operator or the += operator.

//Using the + operator:
let s = "Dev"; //string literal
let t = "Ops";
let result = s + " " + t;
console.log(result); // "Dev Ops"

//Using the += operator:
let u = "Hello";
u += " World";
console.log(u); // "Hello World"