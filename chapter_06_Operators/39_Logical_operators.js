
//logical operators are used to combine multiple conditions or expressions and return a boolean value (true or false). The logical operators in JavaScript are:
//&& (logical AND)
//|| (logical OR)
//! (logical NOT)
let a = true;
let b = false;
console.log(a && b); //false (both conditions must be true)
console.log(a || b); //true (at least one condition is true)
console.log(!a); //false (logical NOT operator)