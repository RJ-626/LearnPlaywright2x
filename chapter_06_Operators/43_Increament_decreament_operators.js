//Pre increament -Increase the value first and then assign it.
let a = 10;
let b = ++a
console.log(b); // Output: 11
console.log(a); // Output: 11

//Post increament - Assign the value first and then increase it.
let c = 20;
let d = c++
console.log(d); // Output: 20
console.log(c); // Output: 21

//predecreament - Decrease the value first and then assign it.
let e = 30;
let f = --e
console.log(f); // Output: 29
console.log(e); // Output: 29

//postdecreament - Assign the value first and then decrease it.
let g = 40;
let h = g--
console.log(h); // Output: 40
console.log(g); // Output: 39
