//type of operator
let num = 42;
console.log(typeof num); // Output: number

let str = "Hello, World!";
console.log(typeof str); // Output: string

let isTrue = true;
console.log(typeof isTrue); // Output: boolean

let myNull = null;
console.log(typeof myNull); // Output: object (this is a known quirk in JavaScript)

let myUndefined = undefined;
console.log(typeof myUndefined); // Output: undefined

let myObject = {};
console.log(typeof myObject); // Output: object

let myArray = [];
console.log(typeof myArray); // Output: object