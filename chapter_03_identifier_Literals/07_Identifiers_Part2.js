// 1. camelCase - first word lowercase, subsequent words capitalized
// Commonly used for variables and functions
let myVariableName = "camelCase example";
let calculateTotalAmount = "camelCase function name example";
console.log("myVariableName:", myVariableName);
console.log("calculateTotalAmount:", calculateTotalAmount);

// 2. PascalCase - every word starts with uppercase
// Commonly used for class names and constructor functions
let MyClassName = "PascalCase example";
let UserProfileInfo = "PascalCase class-like name";
console.log("MyClassName:", MyClassName);
console.log("UserProfileInfo:", UserProfileInfo);

// 3. snake_case - all lowercase with underscores
// Less common in JS, but used in some libraries
let user_profile_info = "snake_case example";
let total_amount_paid = "snake_case variable";
console.log("user_profile_info:", user_profile_info);
console.log("total_amount_paid:", total_amount_paid);

// 4. UPPER_SNAKE_CASE (SCREAMING_SNAKE_CASE) - all uppercase with underscores
// Used for constants
const MAX_VALUE = "UPPER_SNAKE_CASE example";
const API_BASE_URL = "UPPER_SNAKE_CASE constant";
console.log("MAX_VALUE:", MAX_VALUE);
console.log("API_BASE_URL:", API_BASE_URL);

// 5. Hungarian notation - prefix indicates type
// Older style, generally not recommended in modern JS
let strUserName = "Hungarian notation - string";
let bIsActive = "Hungarian notation - boolean";
let nCount = "Hungarian notation - number";
console.log("strUserName:", strUserName);
console.log("bIsActive:", bIsActive);
console.log("nCount:", nCount);
